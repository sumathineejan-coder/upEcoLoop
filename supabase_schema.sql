-- Run once in Supabase Dashboard > SQL Editor.
-- All application tables are private to the backend; do not grant anon access.
CREATE TABLE IF NOT EXISTS public.users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 public_id TEXT NOT NULL CHECK (public_id ~ '^[0-9]{5,20}$'),
 role TEXT NOT NULL CHECK (role IN ('student','merchant')),
 password_hash TEXT NOT NULL,
 name TEXT NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(public_id,role)
);
CREATE TABLE IF NOT EXISTS public.sessions (
 token_hash TEXT PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
 expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_user_idx ON public.sessions(user_id);
CREATE TABLE IF NOT EXISTS public.verification_codes (
 code TEXT PRIMARY KEY CHECK (code ~ '^[0-9]{6}$'),
 student_user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
 expires_at BIGINT NOT NULL,
 used_at BIGINT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS codes_student_idx ON public.verification_codes(student_user_id);
CREATE TABLE IF NOT EXISTS public.transactions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_user_id BIGINT NOT NULL REFERENCES public.users(id),
 merchant_user_id BIGINT NOT NULL REFERENCES public.users(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS tx_student_idx ON public.transactions(student_user_id,id DESC);
CREATE INDEX IF NOT EXISTS tx_merchant_idx ON public.transactions(merchant_user_id,id DESC);
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.verification_codes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.transactions ENABLE ROW LEVEL SECURITY;
-- No policies for anon/authenticated: access is only through trusted backend DB connection.
